/** Builds a screenshot array from the sequential shot-01.png … files in a folder. */
function shots(folder: string, count: number): string[] {
  return Array.from({ length: count }, (_, i) =>
    `/assets/images/${folder}/shot-${String(i + 1).padStart(2, '0')}.png`
  );
}

